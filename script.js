function applyMenuTaxonomy(source) {
  const menu = source || [];
  const drinks = menu.find(category => category.id === "icecekler");
  if (drinks && !drinks.groups) {
    drinks.items = firebaseList(drinks.items);
    const regularIndex = drinks.items.findIndex(item => item.name === "Red Bull");
    const largeIndex = drinks.items.findIndex(item => item.name === "Red Bull Büyük");
    if (regularIndex > -1 && largeIndex > -1 && largeIndex !== regularIndex + 1) {
      const [large] = drinks.items.splice(largeIndex, 1);
      const currentRegularIndex = drinks.items.findIndex(item => item.name === "Red Bull");
      drinks.items.splice(currentRegularIndex + 1, 0, large);
    }
  }
  const main = menu.find(category => category.id === "ana-yemekler");
  if (main) main.title = "Ana Yemek";
  const raki = menu.find(category => category.id === "rakilar");
  if (raki && raki.groups) {
    const wrongIndex = raki.groups.findIndex(group => group.title === "İstanbul");
    if (wrongIndex > -1) {
      const blue = raki.groups.splice(wrongIndex, 1)[0];
      blue.items = firebaseList(blue.items).map(item => ({...item, description: String(item.description || "").replace("İstanbul Rakı", "İstanbul Blue Vodka")}));
      let vodka = menu.find(category => category.id === "votkalar");
      if (!vodka) {
        vodka = { id: "votkalar", title: "Votkalar", image: "image/gin.webp", groups: [] };
        menu.splice(menu.indexOf(raki) + 1, 0, vodka);
      }
      vodka.groups = vodka.groups || [];
      if (!vodka.groups.some(group => group.title === "İstanbul Blue")) {
        vodka.groups.push({...blue, title: "İstanbul Blue"});
      }
    }
  }
  return menu;
}

menuData = window.applyGDZProductImages(applyMenuTaxonomy(menuData));

function firebaseList(value) {
  if (Array.isArray(value)) return value;
  if (!value || typeof value !== "object") return [];
  return Object.keys(value).sort((a, b) => Number(a) - Number(b)).map(key => value[key]).filter(Boolean);
}

function normalizeFirebaseMenu(value) {
  return firebaseList(value).map(category => {
    if (category.groups) {
      category.groups = firebaseList(category.groups).map(group => ({...group, items: firebaseList(group.items)}));
    } else {
      category.items = firebaseList(category.items);
    }
    return category;
  });
}

